#!/usr/bin/env python3
"""Generate the NASM app table consumed by the Burrows launcher."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs" / "app-catalog.json"
OUTPUT = ROOT / "programs" / "generated_app_catalog.inc"


def nasm_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render(catalog: dict) -> str:
    apps = sorted(catalog.get("apps", []), key=lambda item: (item.get("category", ""), item.get("name", "")))
    lines = [
        "; Generated by tools/generate_launcher_catalog.py; do not edit manually.",
        f"APP_CATALOG_COUNT equ {len(apps)}",
        "section .data",
        "",
    ]
    for index, app in enumerate(apps):
        search_parts = [
            app["entry"],
            app["name"],
            app.get("category", ""),
            app.get("description", ""),
            *app.get("keywords", []),
        ]
        search_text = " ".join(part for part in search_parts if part)
        lines.append(f"app_exec_{index}:  db {nasm_string(app['entry'])}, 0")
        lines.append(f"app_label_{index}: db {nasm_string(app['name'])}, 0")
        lines.append(f"app_search_{index}: db {nasm_string(search_text)}, 0")
    lines.extend(["", "app_exec_table:"])
    lines.extend(f"        dd app_exec_{index}" for index in range(len(apps)))
    lines.extend(["", "app_label_table:"])
    lines.extend(f"        dd app_label_{index}" for index in range(len(apps)))
    lines.extend(["", "app_search_table:"])
    lines.extend(f"        dd app_search_{index}" for index in range(len(apps)))
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the NASM Burrows launcher app catalog")
    parser.add_argument("--check", action="store_true", help="Fail if the generated include is stale")
    args = parser.parse_args()

    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    rendered = render(catalog)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            print(f"[launcher-catalog] FAIL {OUTPUT.relative_to(ROOT)} is stale")
            print("  Run: python3 tools/generate_launcher_catalog.py")
            return 1
        print(f"[launcher-catalog] PASS {OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"[launcher-catalog] WROTE {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
