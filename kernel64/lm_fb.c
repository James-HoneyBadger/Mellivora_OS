/* The sixteen VGA text colours, as 0xRRGGBB. */
static const u32 palette[16] = {
    0x000000, 0x0000AA, 0x00AA00, 0x00AAAA, 0xAA0000, 0xAA00AA, 0xAA5500, 0xAAAAAA, 0x555555, 0x5555FF, 0x55FF55, 0x55FFFF, 0xFF5555, 0xFF55FF, 0xFFFF55, 0xFFFFFF
};

struct fb_state {
    volatile u32 *pixels;
    u32 width;
    u32 height;
    u32 pitch_pixels;
    u32 cols;
    u32 rows;
    u32 cursor_col;
    u32 cursor_row;
    u8 format;
    int active;
};

static struct fb_state fb;

static u32 pack_color(u32 rgb, u8 format)
{
    u32 r = (rgb >> 16) & 0xFF;
    u32 g = (rgb >> 8) & 0xFF;
    u32 b = rgb & 0xFF;
    if (format == BOOTINFO_FB_RGBX) {
        return (r << 16) | (g << 8) | b;
    }
    return (b << 16) | (g << 8) | r;      /* BGRX, which VBE 32-bpp is */
}

static inline volatile u32 *row_ptr(u32 y)
{
    return fb.pixels + (u64)y * fb.pitch_pixels;
}

static void fill_rect(u32 x, u32 y, u32 w, u32 h, u32 color)
{
    if (!fb.active) {
        return;
    }
    for (u32 row = 0; row < h; row++) {
        volatile u32 *p = row_ptr(y + row) + x;
        for (u32 col = 0; col < w; col++) {
            p[col] = color;
        }
    }
}

static void draw_glyph(u32 col, u32 row, char c, u32 fg, u32 bg)
{
    u32 index = (u8)c;
    index = (index < 32 || index > 127) ? 0 : index - 32;
    const u8 *bits = glyph_5x7[index];

    u32 x = col * GLYPH_W;
    u32 y = row * GLYPH_H;

    fill_rect(x, y, GLYPH_W, GLYPH_H, bg);
    for (u32 gy = 0; gy < 7; gy++) {
        u8 column_bits = bits[gy];
        if (column_bits == 0) {
            continue;
        }
        volatile u32 *p = row_ptr(y + GLYPH_TOP + gy) + x;
        for (u32 gx = 0; gx < 5; gx++) {
            if (column_bits & (0x10 >> gx)) {
                p[gx] = fg;
            }
        }
    }
}

void fb_console_clear(void)
{
    if (!fb.active) {
        return;
    }
    fill_rect(0, 0, fb.width, fb.height, pack_color(palette[0], fb.format));
    fb.cursor_col = 0;
    fb.cursor_row = 0;
}

static void scroll_one_row(void)
{
    u32 pitch = fb.pitch_pixels;
    u64 keep = (u64)(fb.rows - 1) * GLYPH_H * pitch;

    for (u64 i = 0; i < keep; i++) {
        fb.pixels[i] = fb.pixels[i + (u64)GLYPH_H * pitch];
    }
    fill_rect(0, (fb.rows - 1) * GLYPH_H, fb.width, GLYPH_H,
              pack_color(palette[0], fb.format));
}

void fb_console_putc(char c)
{
    if (!fb.active) {
        return;
    }

    u8 attr = vga_color();
    u32 fg = pack_color(palette[attr & 0x0F], fb.format);
    u32 bg = pack_color(palette[(attr >> 4) & 0x0F], fb.format);

    switch (c) {
    case '\n':
        fb.cursor_col = 0;
        fb.cursor_row++;
        break;
    case '\r':
        fb.cursor_col = 0;
        break;
    case '\t':
        fb.cursor_col = (fb.cursor_col + 8) & ~7u;
        break;
    case '\b':
        if (fb.cursor_col > 0) {
            fb.cursor_col--;
            draw_glyph(fb.cursor_col, fb.cursor_row, ' ', fg, bg);
        }
        break;
    default:
        draw_glyph(fb.cursor_col, fb.cursor_row, c, fg, bg);
        fb.cursor_col++;
        break;
    }

    if (fb.cursor_col >= fb.cols) {
        fb.cursor_col = 0;
        fb.cursor_row++;
    }
    while (fb.cursor_row >= fb.rows) {
        scroll_one_row();
        fb.cursor_row--;
    }
}

int fb_present(void)
{
    return fb.active;
}

/*
 * fb_selftest - prove the mapping and the pitch arithmetic, not just that a
 * mode was set. The probe is the top-left pixel of the console's last cell:
 * inside the panel, so it goes through the same padding and row stride the
 * driver uses, and it is put back immediately. The final pixel of the last
 * scanline is deliberately not used - that one sits at the edge of VRAM, where
 * some emulated adapters drop writes even though the mode is readable.
 */
int fb_selftest(void)
{
    if (!fb.active) {
        return -1;
    }
    volatile u32 *probe_at =
        fb.pixels + (u64)(fb.rows - 1) * GLYPH_H * fb.pitch_pixels +
        (u64)(fb.cols - 1) * GLYPH_W;
    u32 before = *probe_at;
    u32 probe = 0x00FF00FF;

    *probe_at = probe;
    u32 after = *probe_at;
    *probe_at = before;

    if (after != probe) {
        kputs("[fb] FAIL pixel not writable at ");
        kput_dec((fb.rows - 1) * GLYPH_H);
        kputs(",");
        kput_dec((fb.cols - 1) * GLYPH_W);
        kputs("\r\n");
        return -1;
    }

    kputs("[fb] self-test=ok\r\n");
    return 0;
}

u32 fb_width(void)
{
    return fb.active ? fb.width : 0;
}

u32 fb_height(void)
{
    return fb.active ? fb.height : 0;
}

void fb_init(void)
{
    fb.active = 0;
    if (!machine.have_fb || machine.fb_base == 0 || machine.fb_pitch == 0) {
        kputs("[fb] no linear framebuffer (bootinfo=");
        kputs(machine.have_bootinfo ? "v2" : "legacy");
        kputs("), text console only\r\n");
        return;
    }
    if (machine.fb_base + machine.fb_size > 0x100000000ULL) {
        /* The window maps one gigabyte of the aperture and the loader records
         * a 32-bit base, so anything crossing 4 GB is beyond what is there to
         * point at. Say so instead of faulting on the first write. */
        kputs("[fb] framebuffer above 4 GB - using the text console\r\n");
        return;
    }

    fb.pixels = (volatile u32 *)LM_FB_VA(machine.fb_base);
    fb.width = machine.fb_width;
    fb.height = machine.fb_height;
    fb.pitch_pixels = machine.fb_pitch / 4;
    fb.cols = fb.width / GLYPH_W;
    fb.rows = fb.height / GLYPH_H;
    fb.cursor_col = 0;
    fb.cursor_row = 0;
    fb.format = machine.fb_format;
    fb.active = 1;

    fb_console_clear();

    kputs("[fb] ");
    kput_dec(fb.width);
    kputs("x");
    kput_dec(fb.height);
    kputs(" pitch=");
    kput_dec(machine.fb_pitch);
    kputs(" console=");
    kput_dec(fb.cols);
    kputs("x");
    kput_dec(fb.rows);
    kputs(" fb=ok\r\n");
}
