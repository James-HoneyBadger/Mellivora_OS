/*
 * lm_fb.c - the framebuffer console
 *
 * A linear framebuffer is a rectangle of 32-bit pixels and nothing else: no
 * cursor, no attribute byte, no scrolling. Everything a text screen does for
 * free is done here by writing pixels, which is why the glyph is a table and
 * the palette is the VGA one - so that the same characters, in the same
 * colours, reach a person looking at the screen as reach a serial terminal.
 *
 * The region is mapped by the loader at LM_FB_WINDOW (see bootinfo.h); this
 * file only draws.
 */

